// B17 opening clip en la app de PC. Uso: xvfb-run node test/opening-e2e.cjs
const { _electron } = require("/workspace/pwe/node_modules/playwright-core");
const fs = require("fs"), path = require("path");
const UD = "/workspace/avc-testmedia/ud-opening"; fs.rmSync(UD, { recursive: true, force: true });
let fails = 0; const check = (n, ok, d = "") => { console.log(`${ok ? "OK  " : "FALLA"} ${n} ${d}`); if (!ok) fails++; };
const SEL = "[data-opening-clip]";
const launch = (extra = []) => _electron.launch({ executablePath: require(path.join(__dirname, "../node_modules/electron")), args: [path.join(__dirname, ".."), `--user-data-dir=${UD}`, "--no-sandbox", ...extra] });
(async () => {
  let app = await launch(); let w = await app.firstWindow();
  await w.waitForSelector(SEL, { timeout: 8000 });
  const t0 = Date.now();
  check("PC: aparece al abrir", true);
  await w.waitForFunction(() => document.querySelector("#avc-open img")?.naturalWidth > 0, null, { timeout: 2000 }).then(() => check("PC: logo brand/mark.png carga", true), () => check("PC: logo brand/mark.png carga", false));
  await w.waitForSelector(SEL, { state: "detached", timeout: 4000 });
  const dt = Date.now() - t0; check("PC: se va solo (≤ 1.7 s)", dt <= 2000, `${dt} ms (incluye el sondeo del test; tope en código 1700 ms)`);
  await w.reload(); await w.waitForTimeout(800);
  check("PC: una vez por sesión (recargar no lo repite)", (await w.locator(SEL).count()) === 0);
  await app.close();
  app = await launch(); w = await app.firstWindow(); await w.waitForSelector(SEL, { timeout: 8000 });
  await w.mouse.click(400, 300); await w.waitForTimeout(150);
  check("PC: nueva sesión = aparece; clic lo salta", (await w.locator(SEL).count()) === 0);
  await w.locator("[data-open-settings]").first().click(); const sw = w.locator("[data-opening-toggle] input");
  check("PC: interruptor en Ajustes encendido", await sw.isChecked());
  await sw.click(); check("PC: apagar guarda 'off'", (await w.evaluate(() => localStorage.getItem("avc.openingClip"))) === "off");
  await app.close();
  app = await launch(); w = await app.firstWindow(); await w.waitForSelector("[data-open-settings]", { timeout: 8000 }); await w.waitForTimeout(500);
  check("PC: apagado sigue apagado tras reiniciar", (await w.locator(SEL).count()) === 0);
  await w.evaluate(() => localStorage.removeItem("avc.openingClip")); await app.close();
  app = await launch(); w = await app.firstWindow(); await w.waitForSelector(SEL, { timeout: 8000 });
  await w.keyboard.press("Escape"); await w.waitForTimeout(150);
  check("PC: tecla lo salta", (await w.locator(SEL).count()) === 0);
  await app.close();
  app = await launch(); w = await app.firstWindow(); await w.waitForSelector("[data-open-settings]", { timeout: 8000 });
  await w.emulateMedia({ reducedMotion: "reduce" }); await w.evaluate(() => sessionStorage.clear()); await w.reload(); await w.waitForSelector("[data-open-settings]"); await w.waitForTimeout(400);
  const rm = await w.evaluate(() => matchMedia("(prefers-reduced-motion: reduce)").matches);
  check("PC: prefers-reduced-motion: no aparece", (await w.locator(SEL).count()) === 0, `matches=${rm}`);
  await app.close();
  console.log(fails ? `FALLAS: ${fails}` : "TODO OK"); process.exit(fails ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(2); });
